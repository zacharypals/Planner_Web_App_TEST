#!/usr/bin/env node
/* LP Planner build (v5.3.0)
   index.src.html  = the file you edit (JSX, in-page <script type="text/babel">).
   index.html      = what GitHub Pages serves: the same page with the JSX compiled ahead of time,
                     React's smaller production builds, and no in-browser Babel.

   Usage:  node build.js                 → index.html for the TEST app (default)
           node build.js --target live   → index.html for the live app (3 config values swapped)
   Needs:  Node 18+ and `esbuild` (npm i esbuild, or already installed globally). */
const fs = require('fs');
const path = require('path');
let esbuild;
try { esbuild = require('esbuild'); } catch (e) { esbuild = require('/opt/npm-tools/node_modules/esbuild'); }

const target = (process.argv.includes('--target') ? process.argv[process.argv.indexOf('--target') + 1] : 'test');
if (!['test', 'live'].includes(target)) { console.error('--target must be test or live'); process.exit(1); }
const root = __dirname;
let html = fs.readFileSync(path.join(root, 'index.src.html'), 'utf8');

function swapOnce(from, to) {
  const n = html.split(from).length - 1;
  if (n !== 1) { console.error(`build: expected exactly one match, found ${n}: ${from}`); process.exit(1); }
  html = html.replace(from, () => to);
}

// 1. Live differs from TEST by exactly three APP_CONFIG values.
if (target === 'live') {
  swapOnce('Planner_Web_App_TEST/oauth.html', 'Planner_Web_App/oauth.html');
  swapOnce("STORAGE_PREFIX: 'lpt_'", "STORAGE_PREFIX: 'lpd_'");
  swapOnce("ENV_LABEL: 'TEST'", "ENV_LABEL: ''");
  if (html.includes('_TEST')) { console.error('build: "_TEST" still present after live swap'); process.exit(1); }
}

// 2. Compile the one big text/babel block.
const re = /<script type="text\/babel">([\s\S]*?)<\/script>/;
const m = html.match(re);
if (!m) { console.error('build: no <script type="text/babel"> block found'); process.exit(1); }
const out = esbuild.transformSync(m[1], { loader: 'jsx', target: 'es2019', minify: false, legalComments: 'none' });
if (out.warnings.length) console.warn(out.warnings.map(w => w.text).join('\n'));
const js = out.code.replace(/<\/script/gi, '<\\/script');
html = html.replace(re, () => '<script>\n' + js + '</script>');

// 3. React production builds; Babel is no longer needed.
swapOnce('react@18.3.1/umd/react.development.js', 'react@18.3.1/umd/react.production.min.js');
swapOnce('react-dom@18.3.1/umd/react-dom.development.js', 'react-dom@18.3.1/umd/react-dom.production.min.js');
swapOnce('<script src="https://unpkg.com/@babel/standalone@7.26.5/babel.min.js"></script>\n', '');

// 4. Banner so nobody edits the output by mistake.
html = html.replace(/^<!DOCTYPE html>/i, m0 => m0 + '\n<!-- GENERATED by build.js from index.src.html — edit index.src.html, then run: node build.js' + (target === 'live' ? ' --target live' : '') + ' -->');

fs.writeFileSync(path.join(root, 'index.html'), html);
console.log(`built index.html (${target}) — ${(html.length / 1024).toFixed(0)} KB`);
